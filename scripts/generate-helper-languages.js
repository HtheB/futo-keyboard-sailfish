#!/usr/bin/env node
"use strict";

// The UI catalogue and content manifest are the source of truth for runtime
// locale aliases. Do not maintain a second, incomplete dictionary list.
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const root = path.resolve(__dirname, "..");
function load(file, globals = {}) {
    vm.runInNewContext(fs.readFileSync(path.join(root, "layouts", file), "utf8")
        .replace(/^\.pragma .*$/gm, "").replace(/^\.import .*$/gm, ""), globals);
    return globals;
}
const catalogue = load("FutoLanguageCatalogue.js");
const names = load("FutoLanguageData.js", {Catalogue: catalogue, Qt: {locale: () => ({})}});
const manifest = JSON.parse(fs.readFileSync(path.join(root, "content/manifest.json"), "utf8"));
const entries = catalogue.languages.filter(language => language.prediction);
entries.sort((a, b) => a.code === "EN" ? -1 : b.code === "EN" ? 1 : a.code.localeCompare(b.code));
const lines = entries.map(language => {
    const pack = manifest.items.find(item => item.id === "dictionary-" + language.dictionaryPack);
    if (!pack || pack.paths.length !== 1 || !/^dictionaries\/[^/]+\.fksidx$/.test(pack.paths[0]))
        throw new Error("Missing dictionary content for " + language.code);
    if (!language.swipe)
        throw new Error("Dictionary-backed locale lacks swipe registration: " + language.code);
    return `\t{Code: ${JSON.stringify(language.code)}, File: ${JSON.stringify(path.posix.basename(pack.paths[0]))}, Name: ${JSON.stringify(names.localeName(language))}},`;
});
const output = "// Code generated by scripts/generate-helper-languages.js; DO NOT EDIT.\n"
    + "package main\n\nvar supportedLanguages = []languageInfo{\n" + lines.join("\n") + "\n}\n";
const target = path.join(root, "helper/cmd/futo-keyboard-helper/languages_generated.go");
if (process.argv.includes("--check")) {
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== output)
        throw new Error("Runtime language registry is stale; run scripts/generate-helper-languages.js");
} else {
    fs.writeFileSync(target, output);
}
console.log(`Runtime language registry verified: ${entries.length} locales, ${new Set(entries.map(item => item.dictionaryPack)).size} dictionaries.`);
